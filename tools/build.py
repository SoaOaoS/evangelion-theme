#!/usr/bin/env python3
"""Generate every config file of every Evangelion theme from tools/palettes.py.

    python3 tools/build.py            # all themes
    python3 tools/build.py evangelion-rei

Images (backgrounds, intros, previews) are produced by the other scripts in
tools/; this one only writes text configs, the unlock logo and the Neovim
palette module.
"""
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palettes import THEMES  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = [
    "accent", "selection", "muted", None,
    "background", "dark_background", "darker_background", "lighter_background", None,
    "foreground", "dark_foreground", "light_foreground", "bright_foreground", None,
    "red", "yellow", "orange", "green", "cyan", "blue", "magenta", "brown", None,
    "bright_red", "bright_yellow", "bright_green", "bright_cyan", "bright_blue", "bright_magenta",
]


def strip(h):
    return h.lstrip("#").lower()


def rgb(h):
    h = strip(h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, t):
    ra, rb = rgb(a), rgb(b)
    return "#%02x%02x%02x" % tuple(round(ra[i] + (rb[i] - ra[i]) * t) for i in range(3))


class Theme:
    def __init__(self, name, spec):
        self.name = name
        self.spec = spec
        self.c = dict(spec["colors"])
        self.dir = os.path.join(ROOT, spec["dir"])
        self.dark = spec["mode"] == "dark"

    def col(self, role):
        return self.c[role]

    @property
    def gradient(self):
        a, b = (strip(self.col(r)) for r in self.spec["border"])
        return f"rgba({a}ee) rgba({b}ee) {self.spec['border_angle']}deg"

    @property
    def inactive(self):
        return "rgba(%saa)" % strip(mix(self.col("background"), self.col("muted"), 0.45))

    def write(self, rel, text):
        path = os.path.join(self.dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)

    # ------------------------------------------------------------------
    def colors_toml(self):
        notes = self.spec.get("notes", {})
        out = [f"# {self.spec['title']} — Omarchy 4 theme",
               f"# {self.spec['tagline']}",
               "# Generated by tools/build.py from tools/palettes.py.", "",
               f'mode = "{self.spec["mode"]}"', ""]
        for key in ORDER:
            if key is None:
                out.append("")
                continue
            line = f'{key} = "{self.c[key]}"'
            if key in notes:
                line = f"{line:<34}# {notes[key]}"
            out.append(line)
        out += ["", "# Window borders",
                f'hyprland_active_border = "{self.gradient}"',
                f'hyprland_inactive_border = "{self.inactive}"', ""]
        self.write("colors.toml", "\n".join(out))

    # ------------------------------------------------------------------
    def btop(self):
        c, b = self.c, self.spec["btop"]
        hot = [c["green"], c["yellow"], c["red"]] if self.name != "evangelion-eoe" else [c["foreground"], c["orange"], c["red"]]
        lines = {
            "main_bg": "", "main_fg": c["foreground"], "title": c[b["title"]], "hi_fg": c[b["hi"]],
            "selected_bg": c["selection"], "selected_fg": c["bright_foreground"], "inactive_fg": c["muted"],
            "graph_text": c["light_foreground"], "proc_misc": c["cyan"],
            "cpu_box": c[b["box"]], "mem_box": c[b["box"]], "net_box": c[b["box"]], "proc_box": c[b["box"]],
            "div_line": c["selection"],
        }
        grads = {
            "temp": hot, "cpu": hot, "process": hot,
            "free": [c["selection"], c["magenta"], c["bright_magenta"]],
            "cached": [mix(c["background"], c["cyan"], 0.4), c["cyan"], c["bright_cyan"]],
            "available": [mix(c["background"], c["green"], 0.4), c["green"], c["bright_green"]],
            "used": [c["orange"], c["red"], c["bright_red"]],
            "download": [c["blue"], c["magenta"], c["bright_magenta"]],
            "upload": [c["green"], c["yellow"], c["orange"]],
        }
        out = [f"# {self.spec['title']} — btop theme (MAGI system readout)", ""]
        out += [f'theme[{k}]="{v}"' for k, v in lines.items()]
        out.append("")
        for g, (s, m, e) in grads.items():
            out += [f'theme[{g}_start]="{s}"', f'theme[{g}_mid]="{m}"', f'theme[{g}_end]="{e}"']
        self.write("btop.theme", "\n".join(out) + "\n")

    # ------------------------------------------------------------------
    def shell(self):
        c, alert = self.c, self.c[self.spec["alert"]]
        g = self.gradient
        scrim = c["darker_background"] if self.dark else c["foreground"]
        self.write("shell.bar.toml", f"""# Top bar: flat panel, alerts lit in the theme's warning colour.
background       = "{c['background']}"
background-alpha = 1.0
text             = "{c['foreground']}"
active           = "{alert}"
scale-with-font  = true
size-horizontal  = 28
size-vertical    = 30
""")
        for section, alpha in (("menu", 1.0), ("launcher", 0.96)):
            self.write(f"shell.{section}.toml", f"""# {section.title()}: MAGI terminal rows, selected row marked by a thick bar.
background                = "{c['background']}"
background-alpha          = {alpha}
text                      = "{c['foreground']}"
border                    = "{g}"
border-alpha              = 1.0
scrim                     = "{scrim}"
scrim-alpha               = {0.55 if self.dark else 0.25}
selected-background       = "{alert}"
selected-background-alpha = 0.12
selected-text             = "{alert}"
selected-border           = "{alert}"
selected-border-alpha     = 1.0
selected-border-width     = "0 0 0 4"
""")
        self.write("shell.notifications.toml", f"""# NERV alert card: gradient border with a thick left edge.
background        = "{c['background']}"
background-alpha  = 0.96
text              = "{c['foreground']}"
border            = "{g}"
border-alpha      = 1.0
border-width      = 2
border-width-left = 6
countdown         = "{alert}"
""")
        self.write("shell.popups.toml", f"""# Bar flyouts, dropdowns and OSD.
background       = "{c['background']}"
background-alpha = 0.98
text             = "{c['foreground']}"
border           = "{g}"
border-alpha     = 1.0
border-width     = 2
""")
        self.write("shell.lock.toml", f"""# Entry plug lock: idle border, sync gradient while typing, red on failure.
background       = "{c['darker_background']}"
background-alpha = 0.85
text             = "{c['bright_foreground']}"
placeholder      = "{c['dark_foreground']}"
text-error       = "{c['red']}"
border           = "{c[self.spec['border'][0]]}"
border-active    = "{g}"
border-error     = "{c['red']}"
border-alpha     = 1.0
selection        = "{c['accent']}"
selection-alpha  = 0.45
""")

    # ------------------------------------------------------------------
    def hyprland(self):
        a, b = (strip(self.col(r)) for r in self.spec["border"])
        glow = strip(self.col(self.spec["glow"]))
        self.write("hyprland.lua", f"""-- {self.spec['title']}: gradient borders plus an A.T. Field glow on the focused window.
-- Generated by tools/build.py.

local active_border_color = {{ colors = {{ "rgba({a}ee)", "rgba({b}ee)" }}, angle = {self.spec['border_angle']} }}
local inactive_border_color = "{self.inactive}"
local at_field_glow = "rgba({glow}66)"

hl.config({{
  general = {{
    col = {{
      active_border = active_border_color,
      inactive_border = inactive_border_color,
    }},
  }},

  group = {{
    col = {{
      border_active = active_border_color,
      border_inactive = inactive_border_color,
    }},
  }},

  decoration = {{
    shadow = {{
      enabled = true,
      range = 14,
      render_power = 3,
      color = at_field_glow,
      color_inactive = "rgba(00000000)",
    }},
  }},
}})
""")

    def neovim(self):
        self.write("neovim.lua", f"""return {{
  {{
    "SoaOaoS/evangelion-theme",
    name = "evangelion",
    lazy = false,
    priority = 1000,
  }},
  {{
    "LazyVim/LazyVim",
    opts = {{
      colorscheme = "{self.name}",
    }},
  }},
}}
""")

    def small_files(self):
        self.write("icons.theme", self.spec["icons"] + "\n")
        self.write("keyboard.rgb", self.col(self.spec["keyboard"]) + "\n")
        if self.dark:
            path = os.path.join(self.dir, "light.mode")
            if os.path.exists(path):
                os.remove(path)

    def unlock(self):
        logo = Image.open(os.path.join(ROOT, "tools/assets/omarchy-logo.png")).convert("RGBA")
        solid = Image.new("RGBA", logo.size, rgb(self.col(self.spec["logo"])) + (255,))
        solid.putalpha(logo.getchannel("A"))
        solid.save(os.path.join(self.dir, "unlock.png"), optimize=True)

    def build(self):
        os.makedirs(self.dir, exist_ok=True)
        self.colors_toml()
        self.btop()
        self.shell()
        self.hyprland()
        self.neovim()
        self.small_files()
        self.unlock()


def nvim_palettes():
    out = ["-- Generated by tools/build.py from tools/palettes.py. Do not edit.", "return {"]
    for name, spec in THEMES.items():
        out.append(f'  ["{name}"] = {{')
        out.append(f'    mode = "{spec["mode"]}",')
        for k in [k for k in ORDER if k]:
            out.append(f'    {k} = "{spec["colors"][k]}",')
        out.append("  },")
    out.append("}")
    path = os.path.join(ROOT, "lua/evangelion/palettes.lua")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    for name in THEMES:
        with open(os.path.join(ROOT, f"colors/{name}.lua"), "w") as f:
            f.write(f'require("evangelion").load("{name}")\n')


if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "colors"), exist_ok=True)
    wanted = sys.argv[1:] or list(THEMES)
    for name in wanted:
        Theme(name, THEMES[name]).build()
        print("built", name)
    nvim_palettes()
